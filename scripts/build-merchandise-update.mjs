// Perbarui modul Bisnis dan isolasi transaksi khusus ekspor stok di snapshot aktif.
//
//   node scripts/build-merchandise-update.mjs <snapshot-aktif.ts> <sha256-snapshot>
//
// Di snapshot, modul merchandise berupa satu lingkup
//   var merchandiseRoutes = /* @__PURE__ */ (() => { … return merchandiseRoutes2; })();
// hasil supabase/functions/_shared/portal/merchandise.mjs yang memakai pembantu tingkat
// atas snapshot (all, insert, update, has, requireAccess, …). Selain modul ini,
// skrip menyisipkan pemilihan isolasi untuk GET merchandise/stock-export pada
// awal transaksi operasi. Menjalankan ulang pada hasil yang sama bersifat idempoten.
// Hasil ditulis ke supabase/deploy/portal-api/index.ts.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {transform} from './cloud-tools/node_modules/esbuild/lib/main.js';
import {parse} from './cloud-tools/node_modules/acorn/dist/acorn.mjs';

const [sourcePath,expectedHash]=process.argv.slice(2);
if(!sourcePath||!/^[a-f0-9]{64}$/.test(expectedHash||''))throw new Error('Pass active gateway snapshot and its verified SHA-256.');
const source=readFileSync(resolve(sourcePath),'utf8');
const sha=createHash('sha256').update(source).digest('hex');
if(sha!==expectedHash)throw new Error('Active gateway snapshot hash mismatch.');
const once=(text,needle,label)=>{const at=text.indexOf(needle);if(at<0||text.indexOf(needle,at+1)>=0)throw new Error(`Gateway boundary not found exactly once: ${label}`);return at;};

const startMarker='var merchandiseRoutes = /* @__PURE__ */ (() => {\n',endMarker='  return merchandiseRoutes2;\n})();\n';
const start=once(source,startMarker,'merchandise module start'),end=once(source,endMarker,'merchandise module end')+endMarker.length;
if(end<=start)throw new Error('Merchandise module end precedes its start.');
once(source,', purchasingRoutes, merchandiseRoutes]) {','merchandise route handler');

// Modul terbaru tanpa impor: nama yang diimpor dipenuhi pembantu tingkat atas snapshot.
const modulePath=resolve('supabase/functions/_shared/portal/merchandise.mjs');
const moduleSource=readFileSync(modulePath,'utf8');
const imported=[];
let body=moduleSource.replace(/^\/\/ Generated by [^\n]*\n/,'').replace(/^import \{([^}]*)\} from '\.\/(arrays|db|auth)\.mjs';\n/gm,(_,names)=>{
  imported.push(...names.split(',').map(name=>name.trim()).filter(Boolean));return '';
});
if(/^\s*import\b/m.test(body))throw new Error('Unexpected import in merchandise module.');
const exported=[...body.matchAll(/^export\b.*$/gm)].map(m=>m[0]);
if(exported.length!==1||!exported[0].startsWith('export async function merchandiseRoutes('))throw new Error('Merchandise module must export only merchandiseRoutes.');
body=body.replace('export async function merchandiseRoutes(','async function merchandiseRoutes2(');
const code=(await transform(body,{loader:'js',target:'es2022',legalComments:'none'})).code;

// Setiap pembantu yang dipakai harus dideklarasikan tepat di tingkat atas snapshot.
const topLevel=new Set();
for(const node of parse(source,{ecmaVersion:'latest',sourceType:'module'}).body){
  if((node.type==='FunctionDeclaration'||node.type==='ClassDeclaration')&&node.id)topLevel.add(node.id.name);
  if(node.type==='VariableDeclaration')for(const d of node.declarations)if(d.id.type==='Identifier')topLevel.add(d.id.name);
  if(node.type==='ImportDeclaration')for(const s of node.specifiers)topLevel.add(s.local.name);
}
const used=imported.filter(name=>new RegExp(`(?<![\\w$.])${name.replace('$','\\$')}(?![\\w$])`).test(code));
const missing=used.filter(name=>!topLevel.has(name));
if(missing.length)throw new Error(`Snapshot lacks top-level helpers used by merchandise: ${missing.join(', ')}`);

const block=startMarker+code.trimEnd().split('\n').map(line=>line?'  '+line:line).join('\n')+'\n'+endMarker;
let patched=source.slice(0,start)+block+source.slice(end);
// Atur isolasi sebelum SELECT pertama (termasuk autentikasi) pada transaksi ekspor.
const requestStart='      const result = await transaction(client, identity, storage, async (db) => {\n';
const userRead='        const user = await one(db, "SELECT * FROM users WHERE id=? AND status=\'ACTIVE\'"';
const isolation='        if (b.method === "GET" && b.path === "merchandise/stock-export") await db.query("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ");\n';
if(!patched.includes(requestStart+isolation+userRead)){
  const at=once(patched,requestStart+userRead,'authenticated operation transaction')+requestStart.length;
  patched=patched.slice(0,at)+isolation+patched.slice(at);
}
parse(patched,{ecmaVersion:'latest',sourceType:'module'});
const out=resolve('supabase/deploy/portal-api/index.ts');
writeFileSync(out,patched);
console.log(JSON.stringify({source_sha256:sha,output:out,output_sha256:createHash('sha256').update(patched).digest('hex'),
  replaced:{module_bytes:end-start,new_module_bytes:block.length},helpers:used,unchanged:patched===source}));
